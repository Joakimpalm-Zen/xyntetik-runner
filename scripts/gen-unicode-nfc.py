#!/usr/bin/env python3
"""Generate src/unicode_nfc.h: the tables tokenizer.c's NFC normalizer reads.

    scripts/gen-unicode-nfc.py > src/unicode_nfc.h

Qwen's tokenizers (Qwen2 through Qwen3.8, and the models trained on them)
declare {"type": "NFC"} as their normalizer, so the publisher's tokenizer
composes decomposed text before it splits it. The tables come from python's
unicodedata; when the `tokenizers` package is importable every code point is
also normalized by its NFC (the implementation the reference tokenizer runs)
and a code point the two disagree on is left out of the tables, so the C side
follows `tokenizers`. The header records both versions and the exclusions.

Tables:
  ccc   ranges [lo, hi] with their nonzero canonical combining class
  dec   code point -> its full canonical decomposition (Hangul syllables are
        decomposed algorithmically and are not listed)
  comp  (first, second) -> primary composite, for canonical composition
"""

import sys
import unicodedata

MAX = 0x110000
SBASE, SCOUNT = 0xAC00, 11172


def hf_nfc():
    try:
        from tokenizers.normalizers import NFC
        import tokenizers
        return NFC().normalize_str, tokenizers.__version__
    except Exception:
        return None, None


def main():
    nfc_hf, hf_version = hf_nfc()
    # Where the two disagree the C side follows `tokenizers`. Three probes per
    # code point: the character alone, its canonical decomposition composed
    # again (a newer composition `tokenizers` does not know leaves the
    # decomposed text alone), and for a combining mark its reordering against
    # U+0316 (class 220) and U+0334 (class 1), which only happens for a class
    # the implementation knows.
    excluded, ccc_unknown = [], set()
    if nfc_hf:
        py = lambda t: unicodedata.normalize("NFC", t)
        for cp in range(MAX):
            if 0xD800 <= cp <= 0xDFFF:
                continue
            c = chr(cp)
            d = unicodedata.normalize("NFD", c)
            if py(c) != nfc_hf(c) or py(d) != nfc_hf(d):
                excluded.append(cp)
            if unicodedata.combining(c):
                for probe in ("a\u0316" + c, "a" + c + "\u0334"):
                    if py(probe) != nfc_hf(probe):
                        ccc_unknown.add(cp)
    skip = set(excluded)

    ccc = []
    for cp in range(MAX):
        if cp in skip or cp in ccc_unknown:
            continue
        k = unicodedata.combining(chr(cp))
        if k and ccc and ccc[-1][2] == k and ccc[-1][1] == cp - 1:
            ccc[-1][1] = cp
        elif k:
            ccc.append([cp, cp, k])

    dec = []
    for cp in range(MAX):
        if cp in skip or SBASE <= cp < SBASE + SCOUNT or 0xD800 <= cp <= 0xDFFF:
            continue
        d = unicodedata.normalize("NFD", chr(cp))
        if d != chr(cp):
            dec.append((cp, [ord(x) for x in d]))

    comp = []
    for cp in range(MAX):
        if cp in skip or SBASE <= cp < SBASE + SCOUNT:
            continue
        m = unicodedata.decomposition(chr(cp))
        if not m or m.startswith("<"):
            continue
        parts = [int(x, 16) for x in m.split()]
        # a primary composite: a two-part canonical mapping that NFC keeps
        # (the composition exclusions, singletons and non-starter
        # decompositions all normalize to something else)
        if len(parts) == 2 and unicodedata.normalize("NFC", chr(cp)) == chr(cp):
            comp.append((parts[0], parts[1], cp))
    comp.sort()

    pool = []
    rows = []
    for cp, d in dec:
        rows.append((cp, len(pool), len(d)))
        pool.extend(d)

    w = sys.stdout.write
    w("// Generated by scripts/gen-unicode-nfc.py; do not edit.\n")
    w(f"// Unicode {unicodedata.unidata_version} (python unicodedata)")
    w(f", cross-checked against tokenizers {hf_version}" if hf_version else "")
    w(f"; {len(excluded)} decomposition(s) and {len(ccc_unknown)} combining class(es) "
      "left out where the two disagree")
    if excluded or ccc_unknown:
        both = sorted(set(excluded) | ccc_unknown)
        w(":\n//   " + " ".join(f"U+{c:04X}" for c in both[:60]))
        if len(both) > 60:
            w(" ...")
    w(".\n#ifndef RUNNER_UNICODE_NFC_H\n#define RUNNER_UNICODE_NFC_H\n\n#include <stdint.h>\n\n")
    w(f"static const uint32_t nfc_ccc[{len(ccc)}][3] = {{\n")
    for lo, hi, k in ccc:
        w(f"    {{0x{lo:X}, 0x{hi:X}, {k}}},\n")
    w("};\n\n")
    w(f"static const uint32_t nfc_dec_pool[{len(pool)}] = {{\n")
    for i in range(0, len(pool), 10):
        w("    " + ", ".join(f"0x{x:X}" for x in pool[i:i + 10]) + ",\n")
    w("};\n\n")
    w(f"// code point, offset into nfc_dec_pool, length\nstatic const uint32_t nfc_dec[{len(rows)}][3] = {{\n")
    for cp, off, n in rows:
        w(f"    {{0x{cp:X}, {off}, {n}}},\n")
    w("};\n\n")
    w(f"// first, second, composite; sorted by (first, second)\nstatic const uint32_t nfc_comp[{len(comp)}][3] = {{\n")
    for a, b, c in comp:
        w(f"    {{0x{a:X}, 0x{b:X}, 0x{c:X}}},\n")
    w("};\n\n#endif\n")


if __name__ == "__main__":
    main()
