#!/usr/bin/env python3
"""Embed src/kernels.ptx into src/kernels_ptx.h as a C string literal.

The PTX is produced by `make ptx` (requires nvcc + MSVC/gcc host compiler,
development machines only); the generated header is committed so normal builds
and CI need no CUDA toolkit.
"""
import os
import re

# EMBED_IN / EMBED_NAME select the compute_80 module (kernels_sm80.ptx ->
# k_ptx80_src) that make ptx embeds beside the compute_75 one.
src = os.environ.get("EMBED_IN") or os.path.join(os.path.dirname(__file__), "..", "src", "kernels.ptx")
# EMBED_OUT redirects the output (used by the drift check to generate to a temp
# without touching the committed header).
dst = os.environ.get("EMBED_OUT") or os.path.join(
    os.path.dirname(__file__), "..", "src", "kernels_ptx.h")

with open(src, encoding="utf-8") as f:
    lines = f.read().split("\n")

# Down-pin the header's .version to 7.8. Drivers hard-reject PTX whose
# .version is newer than their JIT ("compiled with an unsupported toolchain")
# even when every instruction used is an old one, so the stamp stays at the
# lowest ISA the kernels are known to fit in. The stamp is NOT the support
# floor: the PTX is generated by the CUDA 13.0 toolchain (ISA 9.0) and is
# verified to JIT only on CUDA 13.0+ (R580-series) drivers — the documented
# GPU minimum (README "Install"). On older drivers the runner reports the
# JIT failure and falls back to CPU.
for i, ln in enumerate(lines):
    if ln.startswith(".version"):
        lines[i] = ".version 7.8"
        break

# The toolchain the PTX is built with, named in the header (R8.23): the
# pinned versions from tools/ptx-toolchain/versions.txt, the file make-ptx.sh
# and the ptx-reproducible workflow build it from.
def toolchain_line():
    path = os.path.join(os.path.dirname(__file__), "..", "tools", "ptx-toolchain",
                        "versions.txt")
    try:
        with open(path, encoding="utf-8") as f:
            text = f.read()
    except OSError:
        return None
    parts = []
    m = re.search(r"Cuda compilation tools, release [\d.]+, V([\d.]+)", text)
    if m:
        parts.append("nvcc " + m.group(1))
    names = {"cuda-crt-dev_linux-64": "crt", "cuda-cccl_linux-64": "cccl",
             "cuda-cudart-dev_linux-64": "cudart-dev"}
    for ln in text.splitlines():
        key, _, val = ln.partition(": ")
        if key in names:
            parts.append(names[key] + " " + val.split()[0])
    m = re.search(r"host compiler: .*\((conda-forge gcc [\d.-]+)\)", text)
    if m:
        parts.append("host " + m.group(1))
    return ("// Toolchain: " + ", ".join(parts) +
            " (tools/ptx-toolchain/make-ptx.sh with ptx-linux-64.lock).")


name = os.environ.get("EMBED_NAME") or "k_ptx_src"
out = [f"// Generated from {os.path.basename(src).replace('.ptx', '.cu')} via scripts/embed-ptx.py — do not edit."]
if toolchain_line():
    out.append(toolchain_line())
out.append(f"static const char *{name} =")
for ln in lines:
    esc = ln.replace("\\", "\\\\").replace('"', '\\"')
    out.append(f'    "{esc}\\n"')
out.append(";")

with open(dst, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(out) + "\n")
print(f"wrote {dst}")
