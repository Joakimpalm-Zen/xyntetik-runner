#!/usr/bin/env python3
"""The fidelity index (R7.21): every GGUF side Runner measured against a publisher's reference.

    scripts/fidelity-index.py --write    # render docs/fidelity-index.md and site/pages/fidelity.html
    scripts/fidelity-index.py --check    # fail when either differs from its render

Every gold-logits.v4 report under docs/compat-reports is read, and each of its sides
(a file scored against the reference checkpoint the report names) is one row: the
file, the reference at its revision, the window, the mean KLD and margin-qualified
top-1, and the verdict against the bar of docs/fidelity-method.md (mean KLD at most
0.05 and margin-qualified top-1 at least 97%). Failing rows come first.

Nothing is typed but which file a side scored, and only where the report does not
say: a side's own "file" record (gold-logits.py --gguf-a/--repo-a, from R7.21 on),
else docs/fidelity-index.json's join, else a .gguf name that appears exactly once in
the roster (docs/model-tiers.json). A side none of these name is listed as "file not
identified", never dropped, and the page counts them.
"""
import argparse
import html
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
REPO_URL = "https://github.com/Joakimpalm-Zen/xyntetik-runner"
SCHEMA = "xyntetik.runner.gold-logits.v4"
JOIN_SCHEMA = "xyntetik.runner.fidelity-join.v1"
MAX_KLD, MIN_MQ = 0.05, 97.0
MD = pathlib.Path("docs") / "fidelity-index.md"
PAGE = pathlib.Path("site") / "pages" / "fidelity.html"
GENERATED = "generated by scripts/fidelity-index.py from docs/compat-reports; do not edit"


def _gold_reports(reports):
    for p in sorted(reports.rglob("*.json")):
        try:
            d = json.loads(p.read_text(encoding="utf-8"))
        except (ValueError, UnicodeDecodeError):
            continue
        if isinstance(d, dict) and d.get("schema_version") == SCHEMA:
            yield p.relative_to(reports).as_posix(), d


def _roster_names(roster):
    seen = {}
    for row in json.loads(roster.read_text(encoding="utf-8")).get("rows", []):
        for f in row.get("files") or []:
            if f.get("name") and f.get("repo"):
                seen.setdefault(f["name"], []).append({"repo": f["repo"], "name": f["name"],
                                                       "sha256": f.get("sha256")})
    # a name identifies a file only when every pin of it is one file: the same
    # repository and the same sha256 (a name pinned twice could be either)
    return {n: v[0] for n, v in seen.items() if len({(x["repo"], x["sha256"]) for x in v}) == 1}


def _read_with(v, model):
    """The engine a side was read with: its recorded engine (gold-logits from
    R7.21.2 on), else a score file's runner --score, else an endpoint whose
    engine the report does not say."""
    eng = v.get("engine")
    if isinstance(eng, dict) and eng.get("name") and eng["name"] != "unknown":
        return f"{eng['name']} {eng['version']}" if eng.get("version") else eng["name"]
    if str(v.get("endpoint", "")).endswith(".json") or model == "score file":
        return "runner --score"
    return "an HTTP endpoint"


def _check_evidence(reports, key, entry):
    """A join entry is read from its report's own folder: "evidence" names
    FILE:LINE or FILE:FIRST-LAST there, and those lines hold the entry's
    repo, file name and sha256 (when it gives one). None, or a mismatch,
    refuses the join."""
    m = re.fullmatch(r"([\w.\-]+):(\d+)(?:-(\d+))?", str(entry.get("evidence") or ""))
    if not m:
        return "no evidence (FILE:LINE in the report folder)"
    folder = (reports / key.split("#", 1)[0]).parent
    f = folder / m.group(1)
    if not f.is_file():
        return f"evidence file {m.group(1)} is not in {folder.name}"
    lines = f.read_text(encoding="utf-8", errors="replace").splitlines()
    lo, hi = int(m.group(2)), int(m.group(3) or m.group(2))
    text = "\n".join(lines[lo - 1:hi])
    for field in ("repo", "name", "sha256"):
        if entry.get(field) and entry[field] not in text:
            return f"{m.group(0)} does not say its {field} {entry[field]}"
    return None


def collect(reports, join_path, roster):
    join = json.loads(join_path.read_text(encoding="utf-8")) if join_path.exists() else {"sides": {}}
    if join.get("schema_version", JOIN_SCHEMA) != JOIN_SCHEMA:
        raise SystemExit(f"error: {join_path} is not {JOIN_SCHEMA}")
    names = _roster_names(roster)
    bad = []
    for key, entry in sorted(join.get("sides", {}).items()):
        why = _check_evidence(reports, key, entry)
        if why and (reports / key.split("#", 1)[0]).exists():
            bad.append(f"{key}: {why}")
    if bad:
        raise SystemExit("error: join entries not held by their folder:\n  " + "\n  ".join(bad))
    rows, keys, n_reports = [], set(), 0
    for rel, d in _gold_reports(reports):
        n_reports += 1
        s = d["summary"]
        for side, v in sorted(s["sides"].items()):
            key = f"{rel}#{side}"
            keys.add(key)
            model = str(v.get("model") or "")
            ident, how = v.get("file"), "report"
            if not ident and key in join.get("sides", {}):
                ident, how = join["sides"][key], "join"
            if not ident and model in names:
                ident, how = names[model], "roster"
            kld, mq = float(v["mean_kld_vs_gold"]), float(v["margin_qualified_top1_pct"])
            rows.append({
                "key": key, "report": rel, "ident": ident, "how": how if ident else None,
                "label": model or "unnamed", "reference": s.get("hf", ""),
                "positions": int(s.get("positions", 0)),
                "corpus": pathlib.PurePosixPath(str(s.get("corpus", ""))).name,
                "read_with": _read_with(v, model),
                "kld": kld, "mq": mq, "top1": float(v.get("top1_agreement_pct", 0.0)),
                "verdict": "pass" if kld <= MAX_KLD and mq >= MIN_MQ else "fail",
            })
    stale = sorted(set(join.get("sides", {})) - keys)
    if stale:
        raise SystemExit("error: the join names sides no gold-logits report has: " + ", ".join(stale))
    rows.sort(key=lambda r: (r["verdict"] != "fail", -r["kld"], r["label"], r["key"]))
    return rows, n_reports


def _counts(rows, n_reports):
    p = sum(r["verdict"] == "pass" for r in rows)
    u = sum(r["ident"] is None for r in rows)
    files = "the file of 1 is" if u == 1 else f"the files of {u} are"
    return (f"{len(rows)} measured sides in {n_reports} reports: {p} pass, {len(rows) - p} fail; "
            f"{files} not identified")


def _file_text(r):
    if r["ident"] is None:
        return f"file not identified (the report calls it {r['label']})"
    sha = r["ident"].get("sha256")
    return f"{r['ident']['repo']}: {r['ident']['name']}" + (f" (sha256 {sha[:12]})" if sha else "")


INTRO = ("Every GGUF file Runner has scored against its publisher's reference weights, one row per "
         "measurement, pass or fail. A row reads one file against the reference checkpoint at the "
         "revision named, over the window named; the verdict is the bar of the fidelity method, mean "
         "KLD at most 0.05 and margin-qualified top-1 at least 97%, which was set over 2,000 positions, "
         "so a row over fewer positions is a smaller sample read against the same numbers. Failing rows "
         "come first. A side whose report does not say which file it scored is listed as not "
         "identified rather than left out.")


def render_md(rows, n_reports):
    out = [f"<!-- {GENERATED} -->", "", "# Fidelity index", "", INTRO, "",
           f"**{_counts(rows, n_reports)}.** Method: [fidelity-method.md](fidelity-method.md).", "",
           "| verdict | file | reference | positions | mean KLD | margin-qualified top-1 | top-1 | read with | report |",
           "|---|---|---|---:|---:|---:|---:|---|---|"]
    for r in rows:
        out.append(f"| {r['verdict']} | {_file_text(r)} | {r['reference']} | {r['positions']} | "
                   f"{r['kld']:.4f} | {r['mq']:.1f}% | {r['top1']:.1f}% | {r['read_with']} | "
                   f"[{r['key']}](compat-reports/{r['report']}) |")
    return "\n".join(out) + "\n"


def render_page(rows, n_reports):
    e = html.escape
    body = []
    for r in rows:
        link = f"{REPO_URL}/blob/main/docs/compat-reports/{r['report']}"
        body.append(f'<tr class="{r["verdict"]}"><td>{r["verdict"]}</td><td>{e(_file_text(r))}</td>'
                    f"<td>{e(r['reference'])}</td><td>{r['positions']}</td><td>{r['kld']:.4f}</td>"
                    f"<td>{r['mq']:.1f}%</td><td>{r['top1']:.1f}%</td><td>{e(r['read_with'])}</td>"
                    f'<td><a href="{e(link)}">{e(r["key"])}</a></td></tr>')
    return (f"""<!--meta
title: Fidelity index
description: Every GGUF file Runner has scored against its publisher's reference weights, pass or fail, with the window, the reference revision and the numbers.
path: /fidelity/
nav: evidence
-->
<!-- {GENERATED} -->
<section class="page-head">
  <div class="wrap">
    <p class="eyebrow">Evidence</p>
    <h1>Fidelity index</h1>
    <p class="lede">{e(INTRO)}</p>
    <p><strong>{e(_counts(rows, n_reports))}.</strong> Method: <a href="{REPO_URL}/blob/main/docs/fidelity-method.md">fidelity-method.md</a>.</p>
  </div>
</section>
<section class="section">
  <div class="wrap">
    <table class="data">
      <thead><tr><th>verdict</th><th>file</th><th>reference</th><th>positions</th><th>mean KLD</th><th>margin-qualified top-1</th><th>top-1</th><th>read with</th><th>report</th></tr></thead>
      <tbody>
""" + "\n".join("        " + b for b in body) + """
      </tbody>
    </table>
  </div>
</section>
""")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--reports", default=str(ROOT / "docs" / "compat-reports"))
    ap.add_argument("--join", default=str(ROOT / "docs" / "fidelity-index.json"))
    ap.add_argument("--roster", default=str(ROOT / "docs" / "model-tiers.json"))
    ap.add_argument("--out", default=str(ROOT), help="the root the two pages are written under")
    args = ap.parse_args()
    rows, n = collect(pathlib.Path(args.reports), pathlib.Path(args.join), pathlib.Path(args.roster))
    want = {MD: render_md(rows, n), PAGE: render_page(rows, n)}
    out = pathlib.Path(args.out)
    if args.write:
        for rel, text in want.items():
            (out / rel).parent.mkdir(parents=True, exist_ok=True)
            (out / rel).write_text(text, encoding="utf-8")
        print(f"wrote {MD} and {PAGE}: {_counts(rows, n)}")
        return 0
    if args.check:
        bad = [str(rel) for rel, text in want.items()
               if not (out / rel).exists() or (out / rel).read_text(encoding="utf-8") != text]
        for b in bad:
            print(f"{b} differs from its render: run scripts/fidelity-index.py --write", file=sys.stderr)
        if not bad:
            print(f"fidelity index ok: {_counts(rows, n)}")
        return 1 if bad else 0
    ap.print_help()
    return 2


if __name__ == "__main__":
    sys.exit(main())
