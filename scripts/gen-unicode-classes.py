#!/usr/bin/env python3
"""Generate src/unicode_classes.h: the code-point classes the BPE
pre-tokenizers split on.

    scripts/gen-unicode-classes.py > src/unicode_classes.h

The publishers' splits are regexes over \\p{L} (and its Lu, Ll, Lt, Lm, Lo),
\\p{M}, \\p{N} (and its Nd), \\p{P}, \\p{S} and \\s, which the reference tokenizer (Hugging Face
`tokenizers`, Oniguruma underneath) answers from the Unicode database. The
tables come from python's unicodedata (\\s is the White_Space property, which
for every code point above U+007F is str.isspace); when `tokenizers` is
importable every code point from U+0080 up is also asked of its regex engine,
class by class, and a code point the two disagree on takes the engine's
answer, so the C side follows `tokenizers`. The header records both versions
and how many code points the engine decided. ASCII is tokenizer.c's own.

Table: ranges [lo, hi] of one class, in order, for every code point from
U+0080 up that is a letter (by subcategory), a mark, a decimal digit,
another number, punctuation, a symbol or white space; a code point in no
range is "other" (controls, format characters, private use, unassigned).
"""

import sys
import unicodedata

MAX = 0x110000
CLASSES = ("LU", "LL", "LT", "LM", "LO", "M", "ND", "N", "P", "S", "Z")
PATTERNS = {"LU": r"\p{Lu}", "LL": r"\p{Ll}", "LT": r"\p{Lt}", "LM": r"\p{Lm}",
            "LO": r"\p{Lo}", "M": r"\p{M}", "ND": r"\p{Nd}", "N": r"[\p{Nl}\p{No}]",
            "P": r"\p{P}", "S": r"\p{S}", "Z": r"\s"}


def code_points():
    return [c for c in range(0x80, MAX) if not 0xD800 <= c <= 0xDFFF]


def python_class(c):
    ch = chr(c)
    if ch.isspace():
        return "Z"
    g = unicodedata.category(ch)
    if g[0] == "L":
        return g.upper()
    if g == "Nd":
        return "ND"
    return {"M": "M", "N": "N", "P": "P", "S": "S"}.get(g[0])


def engine_classes(cps):
    """{code point: class} as the reference regex engine answers, or None."""
    try:
        import tokenizers
        from tokenizers import Regex, pre_tokenizers
    except Exception:
        return None, None
    text = "".join(map(chr, cps))
    got = {}
    for k, pattern in PATTERNS.items():
        # "removed" drops every match: what is left is the non-members
        kept = bytearray(len(text))
        split = pre_tokenizers.Split(Regex(pattern), behavior="removed")
        for _, (a, b) in split.pre_tokenize_str(text):
            kept[a:b] = b"\1" * (b - a)
        for i, c in enumerate(cps):
            if not kept[i]:
                if c in got:   # the classes are disjoint in Unicode
                    raise SystemExit(f"U+{c:04X} is both {got[c]} and {k} to the engine")
                got[c] = k
    return got, tokenizers.__version__


def main():
    cps = code_points()
    py = {c: python_class(c) for c in cps}
    eng, hf_version = engine_classes(cps)
    decided = []
    if eng is not None:
        for c in cps:
            if eng.get(c) != py[c]:
                decided.append(c)
                py[c] = eng.get(c)
    ranges = []
    for c in cps:
        k = py[c]
        if k is None:
            continue
        if ranges and ranges[-1][2] == k and ranges[-1][1] == c - 1:
            ranges[-1][1] = c
        else:
            ranges.append([c, c, k])
    w = sys.stdout.write
    w("// Generated by scripts/gen-unicode-classes.py; do not edit.\n")
    src = f"Unicode {unicodedata.unidata_version} (python unicodedata)"
    if hf_version:
        src += (f", cross-checked against tokenizers {hf_version}'s regex engine on every code"
                f" point from U+0080; it decided {len(decided)}")
    w(f"// {src}.\n")
    if decided:
        w("//   " + " ".join(f"U+{c:04X}" for c in decided[:40]) + (" ..." if len(decided) > 40 else "") + "\n")
    w("#ifndef RUNNER_UNICODE_CLASSES_H\n#define RUNNER_UNICODE_CLASSES_H\n\n#include <stdint.h>\n\n")
    w("enum { UC_OTHER, " + ", ".join(f"UC_{k}" for k in CLASSES) + " };\n\n")
    w(f"static const uint32_t uc_ranges[{len(ranges)}][3] = {{\n")
    for lo, hi, k in ranges:
        w(f"    {{0x{lo:X}, 0x{hi:X}, UC_{k}}},\n")
    w("};\n\n#endif\n")


if __name__ == "__main__":
    main()
